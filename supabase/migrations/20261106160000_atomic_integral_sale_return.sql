create table if not exists public.sale_return_operations (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null,
  store_id bigint not null,
  venda_id bigint not null,
  customer_id bigint not null,
  employee_id bigint not null,
  created_by_user_id uuid not null,
  operation_key uuid not null,
  request_payload jsonb not null,
  snapshot jsonb not null,
  result jsonb not null,
  created_at timestamptz not null default now(),
  unique(tenant_id, operation_key),
  unique(tenant_id, store_id, venda_id)
);
alter table public.sale_return_operations enable row level security;
revoke all on public.sale_return_operations from public, anon, authenticated;
grant select, insert on public.sale_return_operations to service_role;
grant usage, select on sequence public.sale_return_operations_id_seq to service_role;

create or replace function public.return_sale_integral(
  p_sale_id bigint, p_store_id bigint, p_customer_id bigint, p_employee_id bigint,
  p_items jsonb, p_tenant_id uuid, p_user_id uuid, p_key uuid
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_sale public.vendas%rowtype;
  v_item public.venda_itens%rowtype;
  v_product public.products%rowtype;
  v_variant public.product_variants%rowtype;
  v_previous public.sale_return_operations%rowtype;
  v_items jsonb;
  v_payload jsonb;
  v_snapshot jsonb;
  v_result jsonb;
  v_condition text;
  v_details jsonb;
  v_qty integer;
  v_variant_id bigint;
  v_paid numeric;
  v_required numeric;
  v_outbound numeric;
  v_paid_commissions integer;
begin
  if p_user_id is null or p_tenant_id is null or not exists (
    select 1 from public.profiles p join public.stores s on s.id=p_store_id and s.tenant_id=p.tenant_id
    where p.id=p_user_id and p.tenant_id=p_tenant_id and (p.role='admin' or p.store_id=p_store_id)
  ) then raise exception 'Usuario sem acesso a esta loja.'; end if;
  if not exists(select 1 from public.employees where id=p_employee_id and tenant_id=p_tenant_id
    and store_id=p_store_id and is_active=true) then raise exception 'Funcionario fora da loja ou inativo.'; end if;
  if p_key is null or jsonb_typeof(p_items) is distinct from 'array'
    or jsonb_array_length(p_items) not between 1 and 200 then raise exception 'Itens da devolucao invalidos.'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) x where
    jsonb_typeof(x) is distinct from 'object' or coalesce(x->>'venda_item_id','') !~ '^[1-9][0-9]*$'
    or coalesce(x->>'condicao','') not in ('Intacto','Defeito','Sobra')) then
    raise exception 'Itens da devolucao invalidos.';
  end if;
  if (select count(distinct x->>'venda_item_id') from jsonb_array_elements(p_items) x) <> jsonb_array_length(p_items) then
    raise exception 'Item repetido na devolucao.';
  end if;
  select jsonb_agg(jsonb_build_object('venda_item_id',(x->>'venda_item_id')::bigint,
    'condicao',x->>'condicao','detalhes_sobra',case when x->>'condicao'='Sobra' then x->'detalhes_sobra' else null end)
    order by (x->>'venda_item_id')::bigint) into v_items from jsonb_array_elements(p_items) x;
  v_payload := jsonb_build_object('sale',p_sale_id,'store',p_store_id,'customer',p_customer_id,
    'employee',p_employee_id,'user',p_user_id,'items',v_items);
  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text || ':' || p_key::text,0));
  select * into v_previous from public.sale_return_operations where tenant_id=p_tenant_id and operation_key=p_key;
  if found then
    if v_previous.request_payload is distinct from v_payload then raise exception 'Tentativa ja utilizada com outros dados.'; end if;
    return v_previous.result;
  end if;
  select * into v_sale from public.vendas where id=p_sale_id and store_id=p_store_id and tenant_id=p_tenant_id for update;
  if not found then raise exception 'Venda nao encontrada.'; end if;
  if exists(select 1 from public.sale_return_operations where tenant_id=p_tenant_id and store_id=p_store_id and venda_id=p_sale_id)
    or v_sale.status='Devolvida' then raise exception 'Venda ja devolvida. Consulte seu historico.'; end if;
  if coalesce(v_sale.is_historical_import,false) or v_sale.status is distinct from 'Fechada'
    or v_sale.customer_id is distinct from p_customer_id then raise exception 'A devolucao exige venda fechada nao historica e seu titular atual.'; end if;
  if exists(select 1 from public.customers where id=p_customer_id and lower(trim(coalesce(full_name,'')))='consumidor final') then
    raise exception 'Identifique o cliente titular antes de devolver em carteira. Consumidor Final e um cadastro compartilhado.';
  end if;
  if v_sale.financiamento_id is not null or exists(select 1 from public.financiamento_loja where venda_id=p_sale_id)
    then raise exception 'Devolucao de venda com carne exige revisao do acordo e nao esta disponivel neste fluxo.'; end if;
  if exists(select 1 from public.pix_sale_charges where venda_id=p_sale_id and
    (status in ('CREATING','PENDING','ERROR') or (status='PAID' and settlement_status is distinct from 'COMPLETED'))) then
    raise exception 'Resolva ou cancele a cobranca Pix pendente antes de devolver a venda.';
  end if;

  perform 1 from public.venda_itens where venda_id=p_sale_id order by id for update;
  if jsonb_array_length(v_items) <> (select count(*) from public.venda_itens where venda_id=p_sale_id)
    or exists(select 1 from jsonb_array_elements(v_items) x where not exists (
      select 1 from public.venda_itens i where i.id=(x->>'venda_item_id')::bigint and i.venda_id=p_sale_id
        and i.store_id=p_store_id and i.tenant_id=p_tenant_id)) then
    raise exception 'Selecione todos os itens da venda. Devolucao parcial nao esta disponivel.';
  end if;
  perform 1 from public.pagamentos where venda_id=p_sale_id order by id for update;
  if exists(select 1 from public.pagamentos where venda_id=p_sale_id and
    (tenant_id is distinct from p_tenant_id or store_id is distinct from p_store_id or parcela_id is not null)) then
    raise exception 'Pagamentos inconsistentes. Revise a venda antes de devolver.';
  end if;
  perform public.update_venda_financeiro(p_sale_id);
  select * into v_sale from public.vendas where id=p_sale_id;
  select coalesce(sum(valor_pago),0) into v_paid from public.pagamentos where venda_id=p_sale_id and parcela_id is null;
  if coalesce(v_sale.valor_final,0)<=0 or v_paid <> v_sale.valor_final or coalesce(v_sale.valor_restante,0)<>0 then
    raise exception 'A devolucao exige venda integralmente quitada, sem saldo ou pagamentos excedentes.';
  end if;
  if exists(select 1 from public.wallet_transactions where related_venda_id=p_sale_id
      and operation_type='Credito_Devolucao') or exists(
    select 1 from public.stock_movements where related_venda_id=p_sale_id
      and (tipo='Devolucao' or lower(coalesce(motivo,'')) like '%devolu%')) then
    raise exception 'Ha registros anteriores de devolucao. Revise o historico antes de continuar.';
  end if;
  -- Reserva de OS ou saída direta: não inventar entrada sem comprovar a saída.
  perform 1 from public.stock_movements where related_venda_id=p_sale_id
    or related_os_id in (select id from public.service_orders where venda_id=p_sale_id) order by id for update;
  perform 1 from public.products where id in(select product_id from public.venda_itens where venda_id=p_sale_id) order by id for update;
  perform 1 from public.product_variants where id in(select variant_id from public.venda_itens where venda_id=p_sale_id) order by id for update;
  perform 1 from public.commissions where venda_id=p_sale_id order by id for update;
  if exists(select 1 from public.commissions where venda_id=p_sale_id and
    (tenant_id is distinct from p_tenant_id or store_id is distinct from p_store_id)) then
    raise exception 'Comissoes inconsistentes. Revise a venda antes de devolver.';
  end if;
  select count(*) into v_paid_commissions from public.commissions where venda_id=p_sale_id and status='Pago';
  select jsonb_build_object('sale',to_jsonb(v_sale),
    'items',(select jsonb_agg(to_jsonb(i) order by id) from public.venda_itens i where venda_id=p_sale_id),
    'payments',(select jsonb_agg(to_jsonb(p) order by id) from public.pagamentos p where venda_id=p_sale_id),
    'commissions',(select jsonb_agg(to_jsonb(c) order by id) from public.commissions c where venda_id=p_sale_id),
    'products',(select jsonb_agg(to_jsonb(p) order by id) from public.products p where id in(
      select product_id from public.venda_itens where venda_id=p_sale_id)),
    'variants',(select jsonb_agg(to_jsonb(v) order by id) from public.product_variants v where id in(
      select variant_id from public.venda_itens where venda_id=p_sale_id))) into v_snapshot;

  for v_item in select * from public.venda_itens where venda_id=p_sale_id order by id loop
    select x->>'condicao',x->'detalhes_sobra' into v_condition,v_details
      from jsonb_array_elements(v_items) x where (x->>'venda_item_id')::bigint=v_item.id;
    if v_item.quantidade<=0 then raise exception 'Quantidade do item invalida.'; end if;
    v_qty := v_item.quantidade * case when v_item.unidade='Par' then 2 else 1 end;
    if v_item.product_id is null then
      if v_condition='Sobra' then raise exception 'Sobra exige produto e variante de origem identificados.'; end if;
      continue; -- Item avulso/serviço fica no snapshot, sem entrada fictícia de estoque.
    end if;
    select * into v_product from public.products where id=v_item.product_id and store_id=p_store_id and tenant_id=p_tenant_id;
    if not found then raise exception 'Produto fora da loja ou inexistente.'; end if;
    v_variant_id := v_item.variant_id;
    if v_variant_id is not null then
      select * into v_variant from public.product_variants where id=v_variant_id and product_id=v_product.id
        and store_id=p_store_id and tenant_id=p_tenant_id;
      if not found then raise exception 'Variante de origem invalida.'; end if;
    end if;
    select sum(quantidade * case when unidade='Par' then 2 else 1 end) into v_required
      from public.venda_itens where venda_id=p_sale_id and product_id=v_item.product_id
        and variant_id is not distinct from v_item.variant_id;
    select coalesce(sum(m.quantidade),0) into v_outbound from public.stock_movements m
      where m.product_id=v_item.product_id and m.variant_id is not distinct from v_item.variant_id
        and m.store_id=p_store_id and m.tenant_id=p_tenant_id and m.tipo='Saida'
        and (m.related_venda_id=p_sale_id or m.related_os_id in (
          select id from public.service_orders where venda_id=p_sale_id and store_id=p_store_id and tenant_id=p_tenant_id));
    if v_outbound <> v_required then raise exception 'Saida de estoque nao comprovada para os itens. Revise o historico.'; end if;
    if v_condition='Intacto' then
      update public.products set estoque_atual=coalesce(estoque_atual,0)+v_qty where id=v_product.id;
      if v_variant_id is not null then
        update public.product_variants set estoque_atual=coalesce(estoque_atual,0)+v_qty where id=v_variant_id;
      end if;
    elsif v_condition='Sobra' then
      if v_qty<>1 or v_item.item_tipo is distinct from 'Lente' or v_item.variant_id is null
        or jsonb_typeof(v_details) is distinct from 'object'
        or coalesce(v_details->>'diametro','') !~ '^[0-9]+([.][0-9]+)?$'
        or (v_details->>'diametro')::numeric not between 0.01 and 999
        or coalesce(v_details->>'olho','') not in ('OD','OE') then
        raise exception 'Sobra exige uma lente individual, variante original, diametro e olho validos.';
      end if;
      insert into public.product_variants(product_id,store_id,tenant_id,nome_variante,esferico,cilindrico,
        eixo,adicao,curva_base,is_sobra,diametro,olho,estoque_atual)
        values(v_product.id,p_store_id,p_tenant_id,'Sobra '||(v_details->>'olho')||' Ø'||(v_details->>'diametro'),
          v_variant.esferico,v_variant.cilindrico,v_variant.eixo,v_variant.adicao,v_variant.curva_base,true,
          (v_details->>'diametro')::numeric,v_details->>'olho',1) returning id into v_variant_id;
      update public.products set estoque_atual=coalesce(estoque_atual,0)+1 where id=v_product.id;
    end if;
    -- Defeito já saiu na venda: registrar a perda sem debitar o estoque novamente.
    insert into public.stock_movements(tenant_id,store_id,product_id,variant_id,tipo,quantidade,motivo,
      custo_unitario_momento,registrado_por_id,employee_id,related_venda_id)
      values(p_tenant_id,p_store_id,v_product.id,v_variant_id,
        case when v_condition='Defeito' then 'Perda' else 'Devolucao' end,v_qty,
        format('Devolucao integral Venda #%s item #%s (%s)',p_sale_id,v_item.id,v_condition),
        v_product.preco_custo,p_user_id,p_employee_id,p_sale_id);
  end loop;

  perform public.add_store_credit_atomic(p_store_id,p_customer_id,v_sale.valor_final,
    format('Crédito por devolução integral Venda #%s',p_sale_id),p_employee_id,p_sale_id,p_tenant_id,p_user_id,p_key);
  update public.commissions set status='Estornado',reversal_reason='Devolução integral de Venda',updated_at=now()
    where venda_id=p_sale_id and tenant_id=p_tenant_id and store_id=p_store_id and status='Pendente';
  update public.vendas set status='Devolvida' where id=p_sale_id;
  v_result := jsonb_build_object('sale_id',p_sale_id,'amount',v_sale.valor_final,'paid_commissions',v_paid_commissions,
    'message','Devolução integral concluída. Crédito registrado na carteira.' ||
      case when v_paid_commissions>0 then ' Há comissões já pagas para acerto manual.' else '' end);
  insert into public.sale_return_operations(tenant_id,store_id,venda_id,customer_id,employee_id,
    created_by_user_id,operation_key,request_payload,snapshot,result)
    values(p_tenant_id,p_store_id,p_sale_id,p_customer_id,p_employee_id,p_user_id,p_key,v_payload,v_snapshot,v_result);
  return v_result;
end;
$$;
revoke all on function public.return_sale_integral(bigint,bigint,bigint,bigint,jsonb,uuid,uuid,uuid) from public,anon,authenticated;
grant execute on function public.return_sale_integral(bigint,bigint,bigint,bigint,jsonb,uuid,uuid,uuid) to service_role;

create or replace function public.protect_returned_sale_status()
returns trigger language plpgsql set search_path = public as $$
begin
  if old.status='Devolvida' and (new.status is distinct from old.status or new.customer_id is distinct from old.customer_id) then
    raise exception 'Venda devolvida nao pode ter o status alterado nem o titular transferido por este fluxo.';
  end if;
  return new;
end;
$$;
revoke all on function public.protect_returned_sale_status() from public,anon,authenticated;
drop trigger if exists protect_returned_sale_status on public.vendas;
create trigger protect_returned_sale_status before update of status, customer_id on public.vendas
for each row execute function public.protect_returned_sale_status();

-- Os pagamentos e itens originais sustentam o crédito e o snapshot da devolução.
create or replace function public.protect_returned_sale_details()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_old_sale bigint; v_new_sale bigint;
begin
  if tg_op <> 'INSERT' then v_old_sale := old.venda_id; end if;
  if tg_op <> 'DELETE' then v_new_sale := new.venda_id; end if;
  if exists(select 1 from public.vendas where id in(v_old_sale,v_new_sale) and status='Devolvida') then
    raise exception 'Itens e pagamentos de venda devolvida devem ser preservados.';
  end if;
  if tg_op='DELETE' then return old; end if;
  return new;
end;
$$;
revoke all on function public.protect_returned_sale_details() from public,anon,authenticated;
drop trigger if exists protect_returned_sale_payments on public.pagamentos;
create trigger protect_returned_sale_payments before insert or update or delete on public.pagamentos
for each row execute function public.protect_returned_sale_details();
drop trigger if exists protect_returned_sale_items on public.venda_itens;
create trigger protect_returned_sale_items before insert or update or delete on public.venda_itens
for each row execute function public.protect_returned_sale_details();
