-- O snapshot preserva o lançamento excluído e os recebíveis relacionados.
create table if not exists public.direct_payment_removals (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null,
  store_id bigint not null,
  venda_id bigint not null,
  payment_id bigint not null unique,
  created_by_user_id uuid not null,
  payment_snapshot jsonb not null,
  receivables_snapshot jsonb not null,
  sale_before jsonb not null,
  sale_after jsonb not null,
  created_at timestamptz not null default now()
);
alter table public.direct_payment_removals enable row level security;
revoke all on public.direct_payment_removals from public, anon, authenticated;
grant select, insert on public.direct_payment_removals to service_role;
grant usage, select on sequence public.direct_payment_removals_id_seq to service_role;

create or replace function public.remove_direct_sale_payment(
  p_payment_id bigint, p_sale_id bigint, p_store_id bigint, p_tenant_id uuid, p_user_id uuid
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_sale public.vendas%rowtype;
  v_payment public.pagamentos%rowtype;
  v_receivables jsonb;
  v_after jsonb;
begin
  if p_payment_id is null or p_payment_id <= 0 or p_sale_id is null or p_sale_id <= 0
    or p_store_id is null or p_store_id <= 0 then raise exception 'Identificadores invalidos.'; end if;
  if p_user_id is null or p_tenant_id is null or not exists (
    select 1 from public.profiles p join public.stores s on s.id=p_store_id and s.tenant_id=p.tenant_id
    where p.id=p_user_id and p.tenant_id=p_tenant_id and (p.role='admin' or p.store_id=p_store_id)
  ) then raise exception 'Usuario sem acesso a esta loja.'; end if;

  -- Mesma ordem de bloqueio das operações de carteira e devolução.
  select * into v_sale from public.vendas where id=p_sale_id and store_id=p_store_id
    and tenant_id=p_tenant_id for update;
  if not found then raise exception 'Venda nao encontrada.'; end if;
  if coalesce(v_sale.is_historical_import,false) or v_sale.status is distinct from 'Em Aberto' then
    raise exception 'Reabra uma venda nao historica antes de remover o pagamento. Vendas devolvidas devem ser preservadas.';
  end if;
  select * into v_payment from public.pagamentos where id=p_payment_id and venda_id=p_sale_id
    and store_id=p_store_id and tenant_id=p_tenant_id for update;
  if not found then raise exception 'Pagamento nao encontrado ou ja removido.'; end if;
  if v_payment.parcela_id is not null or v_payment.receipt_operation_id is not null then
    raise exception 'Recebimento de carne deve ser revertido pelo fluxo de parcelas.';
  end if;
  if v_payment.forma_pagamento='Crédito em Loja' then
    raise exception 'Credito em Loja exige a rotina de devolucao da carteira.';
  end if;
  -- Não soltar o vínculo da conciliação: ON DELETE SET NULL permitiria perder
  -- a referência ao recebimento confirmado, sem devolver dinheiro no provedor.
  if v_payment.forma_pagamento='Pix Sicredi' or exists(
    select 1 from public.pix_sale_charges where settlement_pagamento_id=p_payment_id
  ) then raise exception 'Pagamento Pix integrado exige revisao da conciliacao; esta remocao nao estorna o banco.'; end if;

  perform 1 from public.accounts_receivable where origin_payment_id=p_payment_id order by id for update;
  if exists(select 1 from public.accounts_receivable where origin_payment_id=p_payment_id
    and (store_id is distinct from p_store_id or tenant_id is distinct from p_tenant_id)) then
    raise exception 'Recebiveis inconsistentes com a loja/empresa do pagamento. Revise o lancamento.';
  end if;
  select coalesce(jsonb_agg(to_jsonb(r) order by id),'[]'::jsonb) into v_receivables
    from public.accounts_receivable r where origin_payment_id=p_payment_id;

  delete from public.accounts_receivable where origin_payment_id=p_payment_id;
  delete from public.pagamentos where id=p_payment_id and venda_id=p_sale_id
    and store_id=p_store_id and tenant_id=p_tenant_id;
  if not found then raise exception 'Pagamento nao encontrado ou ja removido.'; end if;
  perform public.update_venda_financeiro(p_sale_id);
  select to_jsonb(v) into v_after from public.vendas v where id=p_sale_id;
  insert into public.direct_payment_removals(tenant_id,store_id,venda_id,payment_id,
    created_by_user_id,payment_snapshot,receivables_snapshot,sale_before,sale_after)
    values(p_tenant_id,p_store_id,p_sale_id,p_payment_id,p_user_id,to_jsonb(v_payment),
      v_receivables,to_jsonb(v_sale),v_after);
  return jsonb_build_object('payment_id',p_payment_id,'sale_id',p_sale_id,
    'receivables_removed',jsonb_array_length(v_receivables),'message','Pagamento removido e saldo da venda atualizado.');
end;
$$;
revoke all on function public.remove_direct_sale_payment(bigint,bigint,bigint,uuid,uuid) from public,anon,authenticated;
grant execute on function public.remove_direct_sale_payment(bigint,bigint,bigint,uuid,uuid) to service_role;
