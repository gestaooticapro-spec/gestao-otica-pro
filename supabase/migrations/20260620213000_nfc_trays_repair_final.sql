-- Reparo final do fluxo NFC.
-- Este script foi pensado para bancos onde versões anteriores da estrutura já
-- foram executadas parcial ou incorretamente. Ele pode ser rodado isoladamente.

BEGIN;

CREATE TABLE IF NOT EXISTS public.nfc_trays (
    id TEXT PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
    current_service_order_id BIGINT REFERENCES public.service_orders(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'active',
    created_by_user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.nfc_tray_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tray_id TEXT NOT NULL,
    store_id BIGINT NOT NULL,
    service_order_id BIGINT,
    action TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'nfc_trays'
          AND column_name = 'id'
          AND data_type <> 'text'
    ) THEN
        ALTER TABLE public.nfc_trays
            ALTER COLUMN id DROP DEFAULT;
        ALTER TABLE public.nfc_trays
            ALTER COLUMN id TYPE TEXT USING id::text;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'nfc_tray_events'
          AND column_name = 'tray_id'
          AND data_type <> 'text'
    ) THEN
        ALTER TABLE public.nfc_tray_events
            ALTER COLUMN tray_id TYPE TEXT USING tray_id::text;
    END IF;
END
$$;

ALTER TABLE public.nfc_trays
    ADD COLUMN IF NOT EXISTS current_service_order_id BIGINT;
ALTER TABLE public.nfc_trays
    ADD COLUMN IF NOT EXISTS status TEXT;
ALTER TABLE public.nfc_trays
    ADD COLUMN IF NOT EXISTS created_by_user_id UUID;
ALTER TABLE public.nfc_trays
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ;
ALTER TABLE public.nfc_trays
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ;

ALTER TABLE public.nfc_trays
    ALTER COLUMN status SET DEFAULT 'active';
ALTER TABLE public.nfc_trays
    ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE public.nfc_trays
    ALTER COLUMN updated_at SET DEFAULT now();

UPDATE public.nfc_trays
   SET status = 'active'
 WHERE status IS NULL
    OR status NOT IN ('active', 'inactive', 'lost');

UPDATE public.nfc_trays
   SET created_at = now()
 WHERE created_at IS NULL;

UPDATE public.nfc_trays
   SET updated_at = now()
 WHERE updated_at IS NULL;

ALTER TABLE public.nfc_trays
    ALTER COLUMN status SET NOT NULL;
ALTER TABLE public.nfc_trays
    ALTER COLUMN created_at SET NOT NULL;
ALTER TABLE public.nfc_trays
    ALTER COLUMN updated_at SET NOT NULL;

ALTER TABLE public.nfc_tray_events
    ADD COLUMN IF NOT EXISTS store_id BIGINT;
ALTER TABLE public.nfc_tray_events
    ADD COLUMN IF NOT EXISTS service_order_id BIGINT;
ALTER TABLE public.nfc_tray_events
    ADD COLUMN IF NOT EXISTS action TEXT;
ALTER TABLE public.nfc_tray_events
    ADD COLUMN IF NOT EXISTS metadata JSONB;
ALTER TABLE public.nfc_tray_events
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ;

UPDATE public.nfc_tray_events
   SET metadata = '{}'::jsonb
 WHERE metadata IS NULL;

UPDATE public.nfc_tray_events e
   SET store_id = t.store_id
  FROM public.nfc_trays t
 WHERE e.store_id IS NULL
   AND e.tray_id = t.id;

UPDATE public.nfc_tray_events
   SET created_at = now()
 WHERE created_at IS NULL;

DELETE FROM public.nfc_tray_events
 WHERE tray_id IS NULL
    OR store_id IS NULL
    OR action IS NULL;

DELETE FROM public.nfc_tray_events e
 WHERE NOT EXISTS (
    SELECT 1
      FROM public.nfc_trays t
     WHERE t.id = e.tray_id
 );

ALTER TABLE public.nfc_tray_events
    ALTER COLUMN metadata SET DEFAULT '{}'::jsonb;
ALTER TABLE public.nfc_tray_events
    ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE public.nfc_tray_events
    ALTER COLUMN tray_id SET NOT NULL;
ALTER TABLE public.nfc_tray_events
    ALTER COLUMN store_id SET NOT NULL;
ALTER TABLE public.nfc_tray_events
    ALTER COLUMN action SET NOT NULL;
ALTER TABLE public.nfc_tray_events
    ALTER COLUMN metadata SET NOT NULL;
ALTER TABLE public.nfc_tray_events
    ALTER COLUMN created_at SET NOT NULL;

DO $$
DECLARE
    v_constraint_name TEXT;
BEGIN
    FOR v_constraint_name IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'public.nfc_trays'::regclass
          AND contype = 'c'
          AND conname <> 'nfc_trays_pkey'
    LOOP
        EXECUTE format(
            'ALTER TABLE public.nfc_trays DROP CONSTRAINT %I',
            v_constraint_name
        );
    END LOOP;

    FOR v_constraint_name IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'public.nfc_tray_events'::regclass
          AND contype IN ('c', 'f')
    LOOP
        EXECUTE format(
            'ALTER TABLE public.nfc_tray_events DROP CONSTRAINT %I',
            v_constraint_name
        );
    END LOOP;
END
$$;

ALTER TABLE public.nfc_trays
    ADD CONSTRAINT nfc_trays_status_check
    CHECK (status IN ('active', 'inactive', 'lost'));

ALTER TABLE public.nfc_tray_events
    ADD CONSTRAINT nfc_tray_events_tray_id_fkey
    FOREIGN KEY (tray_id) REFERENCES public.nfc_trays(id) ON DELETE CASCADE;

ALTER TABLE public.nfc_tray_events
    ADD CONSTRAINT nfc_tray_events_store_id_fkey
    FOREIGN KEY (store_id) REFERENCES public.stores(id) ON DELETE CASCADE;

ALTER TABLE public.nfc_tray_events
    ADD CONSTRAINT nfc_tray_events_service_order_id_fkey
    FOREIGN KEY (service_order_id) REFERENCES public.service_orders(id) ON DELETE SET NULL;

ALTER TABLE public.nfc_tray_events
    ADD CONSTRAINT nfc_tray_events_action_check
    CHECK (
        action IN (
            'TRAY_CREATED',
            'OS_LINKED',
            'LENS_RECEIVED',
            'ASSEMBLY_COMPLETED',
            'TRAY_UNLINKED'
        )
    );

WITH duplicated_links AS (
    SELECT id
    FROM (
        SELECT
            id,
            row_number() OVER (
                PARTITION BY current_service_order_id
                ORDER BY updated_at DESC, created_at DESC, id DESC
            ) AS row_num
        FROM public.nfc_trays
        WHERE current_service_order_id IS NOT NULL
    ) ranked
    WHERE row_num > 1
)
UPDATE public.nfc_trays
   SET current_service_order_id = NULL
 WHERE id IN (SELECT id FROM duplicated_links);

CREATE UNIQUE INDEX IF NOT EXISTS idx_nfc_trays_current_os_unique
    ON public.nfc_trays(current_service_order_id)
    WHERE current_service_order_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_nfc_trays_store_id
    ON public.nfc_trays(store_id);

CREATE INDEX IF NOT EXISTS idx_nfc_tray_events_tray_created
    ON public.nfc_tray_events(tray_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_nfc_tray_events_os_created
    ON public.nfc_tray_events(service_order_id, created_at DESC);

ALTER TABLE public.nfc_trays ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nfc_tray_events ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.update_nfc_trays_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS update_nfc_trays_modtime ON public.nfc_trays;
CREATE TRIGGER update_nfc_trays_modtime
    BEFORE UPDATE ON public.nfc_trays
    FOR EACH ROW
    EXECUTE FUNCTION public.update_nfc_trays_updated_at();

CREATE OR REPLACE FUNCTION public.create_nfc_tray(
    p_tray_id TEXT,
    p_store_id BIGINT,
    p_created_by_user_id UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF p_tray_id IS NULL OR length(btrim(p_tray_id)) < 16 OR length(p_tray_id) > 120 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Identificador de bandeja inválido.';
    END IF;

    INSERT INTO public.nfc_trays (
        id, store_id, created_by_user_id, status
    ) VALUES (
        btrim(p_tray_id), p_store_id, p_created_by_user_id, 'active'
    );

    INSERT INTO public.nfc_tray_events (
        tray_id, store_id, action
    ) VALUES (
        btrim(p_tray_id), p_store_id, 'TRAY_CREATED'
    );

    RETURN jsonb_build_object('tray_id', btrim(p_tray_id));
END;
$$;

CREATE OR REPLACE FUNCTION public.link_nfc_tray_os(
    p_tray_id TEXT,
    p_store_id BIGINT,
    p_os_id BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_tray public.nfc_trays%ROWTYPE;
    v_other_tray RECORD;
BEGIN
    IF p_tray_id IS NULL OR length(btrim(p_tray_id)) < 16 OR length(p_tray_id) > 120 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Identificador de bandeja inválido.';
    END IF;

    PERFORM pg_advisory_xact_lock(p_os_id);

    SELECT *
      INTO v_tray
      FROM public.nfc_trays
     WHERE id = p_tray_id
       AND store_id = p_store_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Bandeja não encontrada nesta loja.';
    END IF;

    IF v_tray.status <> 'active' THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A bandeja está inativa ou perdida.';
    END IF;

    IF v_tray.current_service_order_id = p_os_id THEN
        RETURN jsonb_build_object('service_order_id', p_os_id, 'already_linked', true);
    END IF;

    PERFORM 1
      FROM public.service_orders
     WHERE id = p_os_id
       AND store_id = p_store_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Ordem de Serviço não encontrada nesta loja.';
    END IF;

    IF v_tray.current_service_order_id IS NOT NULL THEN
        INSERT INTO public.nfc_tray_events (
            tray_id, store_id, service_order_id, action, metadata
        ) VALUES (
            v_tray.id,
            v_tray.store_id,
            v_tray.current_service_order_id,
            'TRAY_UNLINKED',
            jsonb_build_object('reason', 'tray_reused')
        );
    END IF;

    FOR v_other_tray IN
        UPDATE public.nfc_trays
           SET current_service_order_id = NULL
         WHERE current_service_order_id = p_os_id
           AND id <> p_tray_id
         RETURNING id, store_id
    LOOP
        INSERT INTO public.nfc_tray_events (
            tray_id, store_id, service_order_id, action, metadata
        ) VALUES (
            v_other_tray.id,
            v_other_tray.store_id,
            p_os_id,
            'TRAY_UNLINKED',
            jsonb_build_object('reason', 'os_transferred', 'target_tray_id', p_tray_id)
        );
    END LOOP;

    UPDATE public.nfc_trays
       SET current_service_order_id = p_os_id
     WHERE id = p_tray_id
       AND store_id = p_store_id;

    INSERT INTO public.nfc_tray_events (
        tray_id, store_id, service_order_id, action
    ) VALUES (
        p_tray_id, p_store_id, p_os_id, 'OS_LINKED'
    );

    RETURN jsonb_build_object('service_order_id', p_os_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.advance_nfc_tray(
    p_tray_id TEXT,
    p_store_id BIGINT,
    p_action TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_tray public.nfc_trays%ROWTYPE;
    v_os public.service_orders%ROWTYPE;
    v_event_action TEXT;
    v_now TIMESTAMPTZ := now();
BEGIN
    IF p_action NOT IN ('LENTE_CHEGOU', 'MONTAGEM_CONCLUIDA', 'DESVINCULAR_BANDEJA') THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Ação NFC inválida.';
    END IF;

    SELECT *
      INTO v_tray
      FROM public.nfc_trays
     WHERE id = p_tray_id
       AND store_id = p_store_id
     FOR UPDATE;

    IF NOT FOUND OR v_tray.current_service_order_id IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Nenhuma OS vinculada a esta bandeja.';
    END IF;

    IF v_tray.status <> 'active' THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A bandeja está inativa ou perdida.';
    END IF;

    SELECT *
      INTO v_os
      FROM public.service_orders
     WHERE id = v_tray.current_service_order_id
       AND store_id = p_store_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'A OS vinculada não pertence a esta loja.';
    END IF;

    IF p_action = 'LENTE_CHEGOU' THEN
        IF v_os.dt_montado_em IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A OS já está marcada como montada.';
        END IF;
        IF v_os.dt_lente_chegou IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A chegada da lente já foi confirmada.';
        END IF;

        UPDATE public.service_orders
           SET dt_pedido_em = COALESCE(dt_pedido_em, v_now),
               dt_lente_chegou = v_now
         WHERE id = v_os.id;
        v_event_action := 'LENS_RECEIVED';
    ELSIF p_action = 'MONTAGEM_CONCLUIDA' THEN
        IF v_os.dt_lente_chegou IS NULL THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Confirme primeiro a chegada da lente.';
        END IF;
        IF v_os.dt_montado_em IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A montagem já foi confirmada.';
        END IF;

        UPDATE public.service_orders
           SET dt_pedido_em = COALESCE(dt_pedido_em, COALESCE(dt_lente_chegou, v_now)),
               dt_lente_chegou = COALESCE(dt_lente_chegou, v_now),
               dt_montado_em = v_now
         WHERE id = v_os.id;
        v_event_action := 'ASSEMBLY_COMPLETED';
    ELSE
        IF v_os.dt_montado_em IS NULL THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'A bandeja só pode ser esvaziada após a montagem.';
        END IF;

        UPDATE public.nfc_trays
           SET current_service_order_id = NULL
         WHERE id = v_tray.id;
        v_event_action := 'TRAY_UNLINKED';
    END IF;

    INSERT INTO public.nfc_tray_events (
        tray_id, store_id, service_order_id, action
    ) VALUES (
        v_tray.id, p_store_id, v_os.id, v_event_action
    );

    RETURN jsonb_build_object(
        'service_order_id', v_os.id,
        'action', p_action
    );
END;
$$;

