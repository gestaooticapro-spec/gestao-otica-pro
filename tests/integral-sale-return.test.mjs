const refund=(overrides={})=>{
  const p={sale:10,store:1,customer:20,employee:5,items,tenant,user,key,...overrides}
  return db.query('select return_sale_integral($1,$2,$3,$4,$5,$6,$7,$8) result',
    [p.sale,p.store,p.customer,p.employee,JSON.stringify(p.items),p.tenant,p.user,p.key])
}
const tables=['vendas','venda_itens','pagamentos','customer_wallets','wallet_transactions','products','product_variants','stock_movements','commissions','sale_return_operations']
async function state(){
  const result={}
  for(const table of tables) result[table]=(await db.query(`select to_jsonb(t) value from ${table} t order by id`)).rows.map(x=>x.value)
  return result
}

