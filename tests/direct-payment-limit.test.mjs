function load(file,mocks={},globals={}){
  const nativeRequire=createRequire(import.meta.url),module={exports:{}}
  const code=ts.transpileModule(read(file),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText
  runInNewContext(code,{module,exports:module.exports,FormData,console:{error(){}},
    require:id=>mocks[id]||(['zod','node:crypto'].includes(id)?nativeRequire(id):{}),...globals})
  return module.exports
}

